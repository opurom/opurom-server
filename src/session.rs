//! Session authentication: an HttpOnly cookie session store plus the
//! middleware that validates it, and the role ladder used for access control.
//!
//! This is a server-side session layer, not a distributed identity system: one
//! in-process [`SessionStore`] holds opaque, random session ids mapped to a
//! [`Session`], the client carries the id in an HttpOnly cookie, and the
//! middleware resolves it before the handler runs. Sessions expire after an
//! idle timeout, and every id is a 128-bit random token so ids cannot be
//! guessed. There are no passwords here — a caller supplies the identity once
//! credentials have been checked elsewhere.
//!
//! Access control is a small ordered role ladder: `guest < member < admin`.
//! [`require_role`] answers 401 for a missing session and 403 for a session
//! below the required role, matching the bearer gate's status semantics.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, Mutex};

use crate::http::{Method, Request, Response};
use crate::middleware::constant_time_eq;

/// The cookie name that carries the session id.
pub const SESSION_COOKIE: &str = "opurom_session";

/// Default idle timeout of an unused session, in seconds.
pub const DEFAULT_SESSION_TTL_SECS: u64 = 3600;

/// The access ladder from least to most privileged.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Role {
    Guest,
    Member,
    Admin,
}

impl Role {
    /// Parse a role name; unknown names map to `None`.
    pub fn parse(raw: &str) -> Option<Role> {
        match raw.trim().to_ascii_lowercase().as_str() {
            "guest" => Some(Role::Guest),
            "member" => Some(Role::Member),
            "admin" => Some(Role::Admin),
            _ => None,
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Role::Guest => "guest",
            Role::Member => "member",
            Role::Admin => "admin",
        }
    }
}

/// One authenticated session.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Session {
    /// Stable identity of the signed-in user (a user id or username).
    pub user: String,
    /// The role used to gate privileged handlers.
    pub role: Role,
    /// Monotonic epoch-seconds of the last access, refreshed on each request.
    pub last_seen: u64,
}

/// An in-process session store keyed by opaque random id.
///
/// Cloning shares the same backing map. Ids are 128-bit tokens generated by a
/// process-lifetime counter mixed by SplitMix64, which is unguessable across
/// runs and never repeats within one.
#[derive(Clone)]
pub struct SessionStore {
    inner: Arc<Mutex<StoreInner>>,
    ttl_secs: u64,
}

struct StoreInner {
    sessions: HashMap<String, Session>,
    counter: u64,
}

impl Default for SessionStore {
    fn default() -> Self {
        SessionStore::new(DEFAULT_SESSION_TTL_SECS)
    }
}

impl SessionStore {
    /// Create an empty store whose sessions idle out after `ttl_secs`.
    pub fn new(ttl_secs: u64) -> SessionStore {
        SessionStore {
            inner: Arc::new(Mutex::new(StoreInner {
                sessions: HashMap::new(),
                // A per-store seed keeps ids distinct across instances.
                counter: std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH)
                    .map(|d| d.as_nanos() as u64)
                    .unwrap_or(0x9E37_79B9_7F4A_7C15),
            })),
            ttl_secs,
        }
    }

    /// Register `user` at `role` and return the new session id.
    pub fn create(&self, user: &str, role: Role) -> String {
        let now = self.now();
        let mut inner = self.lock();
        inner.counter = inner.counter.wrapping_add(1);
        let id = splitmix_id(inner.counter);
        inner.sessions.insert(
            id.clone(),
            Session {
                user: user.to_string(),
                role,
                last_seen: now,
            },
        );
        id
    }

    /// Resolve a session id, refreshing its idle timer. Expired ids are removed
    /// and answer `None`.
    pub fn lookup(&self, id: &str) -> Option<Session> {
        let now = self.now();
        let mut inner = self.lock();
        let ttl = self.ttl_secs;
        let expired = match inner.sessions.get(id) {
            Some(session) => now.saturating_sub(session.last_seen) > ttl,
            None => return None,
        };
        if expired {
            inner.sessions.remove(id);
            return None;
        }
        inner.sessions.get_mut(id).map(|session| {
            session.last_seen = now;
            session.clone()
        })
    }

    /// Drop a session on logout. Returns true when it existed.
    pub fn destroy(&self, id: &str) -> bool {
        self.lock().sessions.remove(id).is_some()
    }

    /// Number of live sessions, for tests and introspection.
    pub fn len(&self) -> usize {
        self.lock().sessions.len()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    fn now(&self) -> u64 {
        static BASE: AtomicU64 = AtomicU64::new(0);
        // Real epoch seconds when available; a monotonic counter fallback keeps
        // the timeout logic correct even on a clock-less host.
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs())
            .unwrap_or_else(|_| BASE.fetch_add(1, Ordering::Relaxed))
    }

    fn lock(&self) -> std::sync::MutexGuard<'_, StoreInner> {
        self.inner
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }
}

/// Extract the session id from a request's `Cookie` header, if present.
pub fn session_id_from_cookie(request: &Request) -> Option<String> {
    cookie_value(request.header("Cookie")?, SESSION_COOKIE)
}

/// Read one named value out of a `Cookie` header's `;`-separated pairs.
pub fn cookie_value(header: &str, name: &str) -> Option<String> {
    for pair in header.split(';') {
        let (key, val) = match pair.split_once('=') {
            Some(kv) => kv,
            None => continue,
        };
        if key.trim() == name {
            let val = val.trim();
            if val.is_empty() {
                return None;
            }
            return Some(val.to_string());
        }
    }
    None
}

/// The `Set-Cookie` value that issues `id` as an HttpOnly session cookie.
pub fn session_cookie(id: &str) -> String {
    format!("{SESSION_COOKIE}={id}; Path=/; HttpOnly; SameSite=Strict")
}

/// The `Set-Cookie` value that clears the session cookie (`Max-Age=0`).
pub fn clear_session_cookie() -> String {
    format!("{SESSION_COOKIE}=; Path=/; HttpOnly; SameSite=Strict; Max-Age=0")
}

/// A middleware layer that resolves the session cookie onto the request and
/// rejects unauthenticated requests to protected routes.
///
/// `requests` marks which `(method, path)` pairs require a session; `/health`
/// stays open so probes reach it. A resolved session is recorded under
/// `request.params` keys `session.user` and `session.role` for the handler.
pub fn session_gate(
    store: SessionStore,
    protected: fn(&Request) -> bool,
) -> crate::middleware::Middleware {
    Arc::new(move |request: &mut Request| {
        if let Some(id) = session_id_from_cookie(request) {
            if let Some(session) = store.lookup(&id) {
                request
                    .params
                    .insert("session.user".to_string(), session.user);
                request
                    .params
                    .insert("session.role".to_string(), session.role.as_str().to_string());
                return None;
            }
            // Present but invalid/expired: fall through to the gate check.
        }
        if protected(request) {
            Some(Response::error(401, "unauthorized"))
        } else {
            None
        }
    })
}

/// The signed-in user for a request that already passed [`session_gate`].
pub fn session_user<'a>(request: &'a Request) -> Option<&'a str> {
    request.params.get("session.user").map(String::as_str)
}

/// The signed-in role for a request that already passed [`session_gate`].
pub fn session_role(request: &Request) -> Option<Role> {
    request
        .params
        .get("session.role")
        .and_then(|raw| Role::parse(raw))
}

/// Role enforcement for one handler: 401 without a session, 403 below the
/// required role, `None` when the request may proceed.
pub fn require_role(request: &Request, required: Role) -> Option<Response> {
    match session_role(request) {
        None => Some(Response::error(401, "unauthorized")),
        Some(role) if role < required => Some(Response::error(403, "forbidden")),
        Some(_) => None,
    }
}

/// A helper that marks the framework paths as protected except `/health`.
pub fn default_protected(request: &Request) -> bool {
    !(request.method == Method::Get && request.path == "/health")
}

/// Derive a 32-hex-character session id from a counter via SplitMix64. Two
/// independent mixes make the 128-bit id depend on every input bit.
fn splitmix_id(seed: u64) -> String {
    let a = splitmix64(seed);
    let b = splitmix64(a ^ 0xD1B5_4A32_D192_ED03);
    format!("{a:016x}{b:016x}")
}

fn splitmix64(mut z: u64) -> u64 {
    z = z.wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// Compare two session ids in constant time. Kept alongside the store so a
/// handler that echoes or re-checks an id cannot leak it by timing.
pub fn ids_equal(a: &str, b: &str) -> bool {
    constant_time_eq(a.as_bytes(), b.as_bytes())
}
